export type FocusKey = keyof Dict;
export type FocusDict = Dict;
export type FocusLang = 'en' | 'zh-TW';

export const focusStrings: Record<FocusLang, Dict> = { en, 'zh-TW': zh };

export function focusLang(lang: string): FocusLang {
  return lang === 'zh-TW' ? 'zh-TW' : 'en';
}

/**
 * Looks up a string and fills placeholders. When `n` is 1 and a `<key>.one`
 * variant exists, that singular form is used (English plurals).
 */
export function translate(dict: Record<string, string>, key: string, params?: Record<string, string | number>): string {
  const singular = params && Number(params.n) === 1 ? dict[`${key}.one`] : undefined;
  return fill(singular ?? dict[key] ?? (en as Record<string, string>)[key] ?? key, params);
}

export function useFocusT(lang: string) {
  const dict = focusStrings[focusLang(lang)] as Record<string, string>;
  return (key: FocusKey, params?: Record<string, string | number>) => translate(dict, key, params);
}

